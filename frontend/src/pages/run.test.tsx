import { screen, waitFor, within } from '@testing-library/react'
import { http, HttpResponse } from 'msw'
import { describe, expect, it } from 'vitest'

import * as f from '../test/fixtures'
import { renderApp } from '../test/render'
import { API, server, sseResponse } from '../test/server'

const RUN_PATH = `/runs/${f.RUN_ID}`

describe('run detail', () => {
  it('shows the meeting header with facts from its metadata', async () => {
    renderApp(RUN_PATH)
    expect(
      await screen.findByRole('heading', { level: 1, name: 'test_hindi.wav' }),
    ).toBeInTheDocument()
    expect(await screen.findByText('2 speakers')).toBeInTheDocument()
    expect(screen.getByText('Code-Mixed, English, Hindi')).toBeInTheDocument()
  })

  it('renders the transcript with speakers, language tags and correct lang attributes', async () => {
    renderApp(RUN_PATH)
    const transcript = await screen.findByRole('list', { name: 'Transcript' })
    const items = within(transcript).getAllByRole('listitem')
    expect(items).toHaveLength(4)
    expect(within(items[0]!).getByText('Speaker 00')).toBeInTheDocument()
    expect(within(items[0]!).getByText('Hindi')).toBeInTheDocument() // sr-only full label
    expect(within(items[0]!).getByText(/namaste sabko/)).toHaveAttribute('lang', 'hi-Latn')
    expect(within(items[3]!).getByText('Unknown speaker')).toBeInTheDocument()
    expect(screen.getByText(/normalized to Romanized Hinglish/)).toBeInTheDocument()
  })

  it('switches to the original Devanagari script', async () => {
    const { user } = renderApp(RUN_PATH)
    await screen.findByRole('list', { name: 'Transcript' })
    await user.click(screen.getByRole('radio', { name: 'Original script' }))
    const line = await screen.findByText('नमस्ते सबको, मीटिंग शुरू करते हैं')
    expect(line).toHaveAttribute('lang', 'hi')
  })

  it('searches within the transcript and highlights matches', async () => {
    const { user } = renderApp(RUN_PATH)
    await screen.findByRole('list', { name: 'Transcript' })
    await user.type(screen.getByLabelText('Search the transcript'), 'release')
    expect(screen.getByText('2 of 4 segments match')).toBeInTheDocument()
    expect(document.querySelectorAll('mark')).toHaveLength(2)
  })

  it('offers seeking for batch runs with a recording', async () => {
    const { container } = renderApp(RUN_PATH)
    expect(await screen.findByRole('button', { name: 'Play from 0:03' })).toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Play' })).toBeInTheDocument()
    expect(screen.getByRole('slider', { name: /Recording position/ })).toBeInTheDocument()
    expect(container.querySelector('audio')?.getAttribute('src')).toMatch(
      /\/api\/runs\/[^/]+\/audio$/,
    )
  })

  it('cycles the playback speed', async () => {
    const { user } = renderApp(RUN_PATH)
    const speed = await screen.findByRole('button', { name: /Playback speed 1×/ })
    await user.click(speed)
    expect(screen.getByRole('button', { name: /Playback speed 1.25×/ })).toBeInTheDocument()
  })

  it('opens at a linked moment with that line current and filling in', async () => {
    renderApp(`${RUN_PATH}?t=4`)
    const current = await screen.findByRole('listitem', { current: true })
    expect(current).toHaveTextContent('Let us review the release plan first')
    expect(screen.getByRole('slider', { name: /Recording position/ })).toHaveAttribute(
      'aria-valuetext',
      expect.stringMatching(/^0:04 of /),
    )
  })

  it('explains a missing summary with the stage error instead of showing nothing', async () => {
    const { user } = renderApp(RUN_PATH)
    await user.click(await screen.findByRole('tab', { name: /Summary/ }))
    expect(await screen.findByText('No summary')).toBeInTheDocument()
    expect(
      screen.getByText(/Summary failed: LLMError: Ollama is not reachable/),
    ).toBeInTheDocument()
    expect(await screen.findByText('Action items was skipped.')).toBeInTheDocument()
  })

  it('shows a produced summary with its action items and a model caveat', async () => {
    server.use(
      http.get(API('/api/runs/:runId/summary'), () => HttpResponse.json(f.summary)),
      http.get(API('/api/runs/:runId/action-items'), () => HttpResponse.json(f.actionItems)),
    )
    const { user } = renderApp(`${RUN_PATH}?tab=summary`)
    expect(await screen.findByText(f.summary.summary)).toBeInTheDocument()
    expect(screen.getByText(/Generated by a language model \(qwen2\.5:7b\)/)).toBeInTheDocument()
    const table = await screen.findByRole('table')
    expect(within(table).getByText('Finish testing')).toBeInTheDocument()
    expect(within(table).getByText('Diya')).toBeInTheDocument()
    await user.click(screen.getByRole('tab', { name: /Transcript/ }))
  })

  it('reflects the open tab in the URL', async () => {
    const { user, router } = renderApp(RUN_PATH)
    await user.click(await screen.findByRole('tab', { name: /Provenance/ }))
    expect(router.state.location.search).toBe('?tab=provenance')
  })

  it('states evaluation eligibility on the provenance tab', async () => {
    server.use(
      http.get(API(`/api/runs/${f.RUN_ID}`), () =>
        HttpResponse.json(
          f.runDetail({
            evaluation_ineligibility:
              'its stages were produced under different configurations (executions [0, 1])',
            consistency: { executions: [0, 1], config: false, code: true },
          }),
        ),
      ),
    )
    renderApp(`${RUN_PATH}?tab=provenance`)
    expect(await screen.findByText('Not eligible for reported results')).toBeInTheDocument()
    expect(screen.getByText(/different configurations \(executions \[0, 1\]\)/)).toBeInTheDocument()
    expect(screen.getByText('Mixed configurations')).toBeInTheDocument()
    expect(
      screen.getByText('68a731919988a8a3498cf8724d0ed5c915c4c953fe5904b77de470fe2a7d8bf8'),
    ).toBeInTheDocument()
  })

  it('shows the server refusal verbatim when a resume would mix configurations', async () => {
    const detail =
      'Run x was produced under config 108acd72e0ed, but the current config is 9f0e (changed: ollama_model ...)'
    server.use(
      http.post(API('/api/runs/:runId/resume'), () =>
        HttpResponse.json({ detail }, { status: 409 }),
      ),
    )
    const { user } = renderApp(RUN_PATH)
    await user.click(await screen.findByRole('button', { name: 'Resume' }))
    const dialog = await screen.findByRole('dialog')
    await user.click(within(dialog).getByRole('button', { name: 'Resume' }))
    expect(await within(dialog).findByText(detail)).toBeInTheDocument()
  })

  it('follows progress while a job is running, then reloads when it ends', async () => {
    let finished = false
    server.use(
      http.get(API(`/api/runs/${f.RUN_ID}`), () =>
        HttpResponse.json(
          finished
            ? f.runDetail({ status: 'completed' })
            : f.runDetail({ job: f.job(), stages: f.stages.slice(0, 2) }),
        ),
      ),
      http.get(API(`/api/runs/${f.RUN_ID}/events`), () => {
        finished = true
        return sseResponse(
          [
            ['job', f.job()],
            ['manifest', { status: 'partial', stages: f.stages.slice(0, 3), extra: {} }],
            ['job', f.job({ state: 'finished' })],
            ['end', { run_id: f.RUN_ID }],
          ],
          { delayMs: 20 },
        )
      }),
    )
    renderApp(RUN_PATH)
    expect(await screen.findByText('Processing')).toBeInTheDocument()
    expect(await screen.findByText(/stages done/)).toBeInTheDocument()
    // After `end` the run is refetched: completed, no progress panel.
    expect(await screen.findByText('Completed')).toBeInTheDocument()
    expect(screen.queryByText('Processing')).not.toBeInTheDocument()
  })

  it('says so when the run does not exist', async () => {
    renderApp('/runs/nope')
    expect(await screen.findByText('Meeting not found')).toBeInTheDocument()
  })
})

describe('run detail: guideline fixes', () => {
  it('asks for a stage instead of disabling re-run on a completed run', async () => {
    server.use(
      http.get(API(`/api/runs/${f.RUN_ID}`), () =>
        HttpResponse.json(f.runDetail({ status: 'completed' })),
      ),
    )
    const { user } = renderApp(RUN_PATH)
    await user.click(await screen.findByRole('button', { name: 'Re-run' }))
    const dialog = await screen.findByRole('dialog')
    await user.click(within(dialog).getByRole('button', { name: 'Resume' }))
    expect(within(dialog).getByText('Choose a stage to re-run.')).toBeInTheDocument()
    expect(within(dialog).getByLabelText('Re-run from stage')).toHaveFocus()
  })

  it('keeps expanded artifacts in the URL', async () => {
    const { user, router } = renderApp(`${RUN_PATH}?tab=artifacts`)
    await user.click(await screen.findByRole('button', { name: /Language tagging/ }))
    expect(router.state.location.search).toContain('open=tagged')
    expect(await screen.findByRole('region', { name: 'tagged JSON' })).toBeInTheDocument()
  })

  it('opens artifacts named in the URL', async () => {
    renderApp(`${RUN_PATH}?tab=artifacts&open=tagged`)
    expect(await screen.findByRole('region', { name: 'tagged JSON' })).toBeInTheDocument()
  })

  it('shows a legend for the language codes', async () => {
    renderApp(RUN_PATH)
    await screen.findByRole('list', { name: 'Transcript' })
    // The visible key, not the badges' screen-reader labels.
    expect(screen.getByText('Code-mixed', { ignore: '.sr-only' })).toBeVisible()
  })
})

describe('pipeline view', () => {
  it('shows how the meeting was processed, stage by stage', async () => {
    renderApp(`${RUN_PATH}?tab=provenance`)
    expect(
      await screen.findByRole('heading', { name: 'How this meeting was processed' }),
    ).toBeInTheDocument()
    const stages = screen.getByRole('list', { name: 'Pipeline stages' })
    expect(within(stages).getByText(/Transcribe/)).toBeInTheDocument()
    expect(within(stages).getByText(/\(Summary\): failed/)).toBeInTheDocument()
  })
})

describe('deleting a meeting', () => {
  it('asks first, then deletes and returns to the meeting list', async () => {
    let deleted = ''
    server.use(
      http.delete(API('/api/runs/:runId'), ({ params }) => {
        deleted = String(params.runId)
        return new HttpResponse(null, { status: 204 })
      }),
    )
    const { user, router } = renderApp(RUN_PATH)
    await user.click(await screen.findByRole('button', { name: 'Delete' }))
    const dialog = await screen.findByRole('dialog', { name: 'Delete this meeting?' })
    expect(within(dialog).getByText(/cannot be undone/)).toBeInTheDocument()
    expect(deleted).toBe('')

    await user.click(within(dialog).getByRole('button', { name: 'Delete meeting' }))
    await waitFor(() => expect(router.state.location.pathname).toBe('/meetings'))
    expect(deleted).toBe(f.RUN_ID)
  })

  it('shows why the server refused, and keeps the dialog open', async () => {
    const reason =
      'The evaluation report generated 2026-10-11 scores this meeting, so deleting it would leave a reported number without its run.'
    server.use(
      http.delete(API('/api/runs/:runId'), () =>
        HttpResponse.json({ detail: reason }, { status: 409 }),
      ),
    )
    const { user, router } = renderApp(RUN_PATH)
    await user.click(await screen.findByRole('button', { name: 'Delete' }))
    const dialog = await screen.findByRole('dialog')
    await user.click(within(dialog).getByRole('button', { name: 'Delete meeting' }))
    expect(await within(dialog).findByText(reason)).toBeInTheDocument()
    expect(router.state.location.pathname).toBe(RUN_PATH)
  })
})
